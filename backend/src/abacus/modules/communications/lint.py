"""The template text lint (R-01 Story 7.2), the part publish needs (R-01-T19).

Each finding names its rule and where it is (a block id, or `subject`, `preheader`,
`cta_label`), never the text. T19 runs the rules a published version must never break: a
variable the key does not register (or a block variable outside an item list), an amount, a
TIN-shaped number, an account number, the platform's name, and a link or domain in the text or
`{portal_link}` anywhere but the button (security review M3). R-01-T23 adds an attachment (an
email never carries one, so its words are refused: "attached", "enclosed"), a second button (a
bracketed label, "click here", or a block repeating the button's label) and `banned_word` (the
glossary's client-email bans and `scope-guards.yaml`'s banned terms, generated beside this file
as `scope_guard_terms.gen.json`), and the lint now runs at preview (findings), test send,
publish and import (refusals), always on the server. Deterministic: the same content gives the
same findings in the same order.
"""

from __future__ import annotations

import json
import re
from dataclasses import dataclass
from functools import cache
from pathlib import Path
from typing import Final, cast

from abacus.modules.communications.render import TemplateContent, used_variables
from abacus.modules.communications.template_registry import (
    ACCOUNT_SHAPE,
    AMOUNT_SHAPE,
    TIN_SHAPE,
    VARIABLES,
    EmailTemplateRegistration,
    LintCode,
    normalised,
)
from abacus.modules.communications.templates import TemplateInvalid

_PLATFORM: Final = re.compile(r"accrued", re.IGNORECASE)
_PLACEHOLDER: Final = re.compile(r"\{[a-z][a-z0-9_]{0,39}\}")
# Security review M3: firm text carries no address of its own; the one link is the button's.
_FOREIGN_LINK: Final = re.compile(
    r"(?i)\b(?:https?://|www\.)|[a-z0-9](?:[a-z0-9-]{0,62})(?:\.[a-z0-9-]{1,63})*\.[a-z]{2,24}\b"
)


_ATTACHMENT: Final = re.compile(
    r"(?i)\b(?:attach(?:ed|es|ing|ment|ments)?|enclos(?:ed|ure|ures))\b"
)
# A call to act other than the one button: a bracketed label or a "click here".
_SECOND_BUTTON: Final = re.compile(
    r"(?i)\bclick (?:here|below|the button|the link)\b|\[[^\]\n]{1,60}\]"
)
# Glossary (R-01-T04, L2 and L7): never in a client email. "AI" is matched as written.
_BANNED_WORDS: Final = re.compile(
    r"(?i)\b(?:agents?|tasks?|issues?|confidence|passwords?|materiality|needs review|in review)\b"
    r"|\bAI\b"
)
_TERMS_FILE: Final = Path(__file__).with_name("scope_guard_terms.gen.json")


@cache
def scope_guard_terms() -> tuple[str, ...]:
    """`scope-guards.yaml`'s banned terms (generated by `scope_guards --write`)."""
    raw = cast(dict[str, list[str]], json.loads(_TERMS_FILE.read_text(encoding="utf-8")))
    return tuple(raw["terms"])


@cache
def _scope_terms() -> re.Pattern[str]:
    """Security review L3: the terms in any case ("planner agent" is still the term), as whole
    words, so a firm's "ACMEs" or "Departmental" is not mistaken for one."""
    words = "|".join(re.escape(t) for t in scope_guard_terms())
    return re.compile(rf"(?<!\w)(?:{words})(?!\w)", re.IGNORECASE)


@dataclass(frozen=True)
class LintFinding:
    code: LintCode
    where: str  # a block id, or subject / preheader / cta_label

    def fact(self) -> str:
        return f"{self.code}:{self.where}"


def _text_findings(where: str, text: str) -> list[LintFinding]:
    bare = normalised(_PLACEHOLDER.sub(" ", text))
    found: list[LintFinding] = []
    if TIN_SHAPE.search(bare):
        found.append(LintFinding("tin_shape", where))
    if ACCOUNT_SHAPE.search(bare):
        found.append(LintFinding("account_number", where))
    if AMOUNT_SHAPE.search(TIN_SHAPE.sub(" ", bare)):
        found.append(LintFinding("amount", where))
    if _PLATFORM.search(bare):
        found.append(LintFinding("platform_name", where))
    if _FOREIGN_LINK.search(bare) or "{portal_link}" in text:
        found.append(LintFinding("foreign_link", where))  # the link goes only in the button
    if _ATTACHMENT.search(bare):
        found.append(LintFinding("attachment", where))
    if where != "cta_label" and _SECOND_BUTTON.search(bare):
        found.append(LintFinding("second_button", where))
    if _BANNED_WORDS.search(bare) or _scope_terms().search(bare):
        found.append(LintFinding("banned_word", where))
    return found


def lint_template(
    content: TemplateContent, registration: EmailTemplateRegistration
) -> list[LintFinding]:
    allowed = set(registration.variables)
    found: list[LintFinding] = []
    parts: list[tuple[str, str, bool]] = [
        ("subject", content.subject, False),
        ("preheader", content.preheader, False),
    ]
    if content.cta_label is not None:
        parts.append(("cta_label", content.cta_label, False))
    parts.extend((b.id, b.text, b.kind == "item_list") for b in content.blocks)
    for where, text, takes_blocks in parts:
        try:
            names = used_variables(text)
        except TemplateInvalid:
            found.append(LintFinding("unregistered_variable", where))
            names = []
        for name in names:
            variable = VARIABLES.get(name)
            if name not in allowed or variable is None or (variable.block and not takes_blocks):
                found.append(LintFinding("unregistered_variable", where))
                break
        found.extend(_text_findings(where, text))
        label = (content.cta_label or "").strip().casefold()
        if label and where != "cta_label" and text.strip().casefold() == label:
            found.append(LintFinding("second_button", where))  # the button, again
    return found
