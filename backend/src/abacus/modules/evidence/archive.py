"""The audit file's archive record, before the seal (A-07-T31; A-07 F7; SPEC-644; DEC-3108).
PROTECTED (red path, chapter 03 §2.2).

`evidence` owns `archives` (0077, widened by 0669) and its insert-only children. It never imports
`assurance` (A-01's rule): assurance's `report.released` consumer calls `open_archive` with the
release's facts, and `assurance/archive_gate.py` computes the checklist and the binder index and
hands the index to `record_binder_index`. The seal and the lock are A-07-T37's.

- **Open.** One v2 archive per work item (0669's unique index), status `assembling`, with the
  release's id, instant and firm-local date. `documentation_completion_date` is generated by the
  database as release date + 60 (AU-C 230). `retention_until` is the longer of the firm's P-14
  policy for `audit_documentation` and the five-year floor (I-RETENTION-FLOOR); with no policy
  the floor stands, and the table's CHECK refuses anything shorter.
- **Binder index.** Insert-only versions (`index_version` 1, 2, …) with the sections and their
  SHA-256; built by code (`built_by_kind = 'code'`), never typed by hand.
"""

from __future__ import annotations

import hashlib
import json
from collections.abc import Mapping, Sequence
from dataclasses import dataclass
from datetime import date, datetime, timedelta
from typing import Final, cast
from uuid import UUID

from sqlalchemy import text

from abacus.kernel.db import TenantContext, tenant_session
from abacus.kernel.uow import Ref, Scope, Target, UnitOfWork
from abacus.modules.evidence.retention import retain_until_for

RECORD_TYPE: Final = "audit_documentation"  # AU-C 230
FLOOR_YEARS: Final = 5


def five_year_floor(release_date: date) -> date:
    """Release + 5 years, Feb 29 → Feb 28 (the CHECK's `interval '5 years'` rounds the same)."""
    try:
        return release_date.replace(year=release_date.year + FLOOR_YEARS)
    except ValueError:
        return release_date.replace(year=release_date.year + FLOOR_YEARS, day=28)


@dataclass(frozen=True)
class ArchiveRow:
    id: UUID
    work_item_id: UUID
    engagement_id: UUID
    status: str
    release_id: UUID
    released_at: datetime
    release_date: date
    documentation_completion_date: date
    retention_until: date
    locked_at: datetime | None
    locked_by: UUID | None
    seal_sha256: str | None


_ROW: Final = text(
    "SELECT id, work_item_id, engagement_id, status, release_id, released_at, release_date, "
    "documentation_completion_date, retention_until, locked_at, locked_by, seal_sha256 "
    "FROM archives WHERE work_item_id = :wi"
)


async def archive_of(tenant: TenantContext, work_item_id: UUID) -> ArchiveRow | None:
    async with tenant_session(tenant) as session:
        row = (await session.execute(_ROW, {"wi": work_item_id})).first()
    return None if row is None else ArchiveRow(*row)


async def open_archive(
    tx: UnitOfWork,
    tenant: TenantContext,
    *,
    engagement_id: UUID,
    work_item_id: UUID,
    release_id: UUID,
    released_at: datetime,
    release_date: date,
    service_line: str,
) -> UUID:
    """`report.released` → Assembling, once per work item (a redelivery finds the row)."""
    found = await tx.session.scalar(
        text("SELECT id FROM archives WHERE work_item_id = :wi"), {"wi": work_item_id}
    )
    if found is not None:
        return cast(UUID, found)
    floor = five_year_floor(release_date)
    policy = await retain_until_for(tenant, RECORD_TYPE, service_line, released_at)
    retention_until = max(floor, policy.date()) if policy is not None else floor
    archive_id = cast(
        UUID,
        await tx.session.scalar(
            text(
                "INSERT INTO archives (tenant_id, engagement_id, work_item_id, release_id, "
                "released_at, release_date, retention_until, status) VALUES (:tenant, "
                ":engagement, :wi, :release, :released_at, :release_date, :retention, "
                "'assembling') RETURNING id"
            ),
            {
                "tenant": tenant.tenant_id,
                "engagement": engagement_id,
                "wi": work_item_id,
                "release": release_id,
                "released_at": released_at,
                "release_date": release_date,
                "retention": retention_until,
            },
        ),
    )
    tx.record(
        "archive.assembly_started",
        target=Target("archive", archive_id),
        after=Ref(
            release=release_id,
            documentation_completion=int((release_date + timedelta(days=60)).strftime("%Y%m%d")),
            retention_until=int(retention_until.strftime("%Y%m%d")),
        ),
        scope=Scope(engagement_id=engagement_id, work_item_id=work_item_id),
    )
    return archive_id


@dataclass(frozen=True)
class BinderSection:
    section: str  # A to H
    title: str
    workpapers: int
    source_documents: int
    run_logs: int
    independence: int = 0

    def canonical(self) -> dict[str, object]:
        return {
            "section": self.section,
            "title": self.title,
            "workpapers": self.workpapers,
            "source_documents": self.source_documents,
            "run_logs": self.run_logs,
            "independence": self.independence,
        }


def index_sha256(sections: Sequence[BinderSection]) -> str:
    body = json.dumps([s.canonical() for s in sections], sort_keys=True, separators=(",", ":"))
    return hashlib.sha256(body.encode()).hexdigest()


async def record_binder_index(
    tx: UnitOfWork,
    archive: ArchiveRow,
    sections: Sequence[BinderSection],
    run_id: UUID | None = None,
) -> int:
    """A new index version (insert-only); the same sections as the latest answer its version."""
    digest = index_sha256(sections)
    latest = (
        await tx.session.execute(
            text(
                "SELECT index_version, sha256 FROM archive_binder_indexes "
                "WHERE archive_id = :a ORDER BY index_version DESC LIMIT 1"
            ),
            {"a": archive.id},
        )
    ).first()
    if latest is not None and latest.sha256 == digest:
        return int(latest.index_version)
    version = 1 if latest is None else int(latest.index_version) + 1
    await tx.session.execute(
        text(
            "INSERT INTO archive_binder_indexes (tenant_id, engagement_id, work_item_id, "
            "archive_id, index_version, sections, sha256, built_by_kind, run_id) VALUES "
            "((SELECT tenant_id FROM archives WHERE id = :a), :engagement, :wi, :a, :v, "
            "CAST(:sections AS jsonb), :sha, 'code', :run)"
        ),
        {
            "a": archive.id,
            "engagement": archive.engagement_id,
            "wi": archive.work_item_id,
            "v": version,
            "sections": json.dumps([s.canonical() for s in sections], sort_keys=True),
            "sha": digest,
            "run": run_id,
        },
    )
    tx.record(
        "archive.binder_index_built",
        target=Target("archive", archive.id),
        after=Ref(index_version=version, sha256=digest),
        scope=Scope(engagement_id=archive.engagement_id, work_item_id=archive.work_item_id),
    )
    return version


async def latest_binder_index(
    tenant: TenantContext, archive_id: UUID
) -> tuple[int, tuple[BinderSection, ...]] | None:
    async with tenant_session(tenant) as session:
        row = (
            await session.execute(
                text(
                    "SELECT index_version, sections FROM archive_binder_indexes "
                    "WHERE archive_id = :a ORDER BY index_version DESC LIMIT 1"
                ),
                {"a": archive_id},
            )
        ).first()
    if row is None:
        return None
    sections = tuple(
        BinderSection(
            str(s["section"]),
            str(s["title"]),
            int(s["workpapers"]),
            int(s["source_documents"]),
            int(s["run_logs"]),
            int(s.get("independence", 0)),
        )
        for s in cast(list[Mapping[str, object]], row.sections)
    )
    return int(row.index_version), sections


async def source_document_count(tenant: TenantContext, engagement_id: UUID) -> int:
    """Section F: the engagement's evidence documents, superseded versions kept (one per object,
    every object that ever had a version on the engagement)."""
    async with tenant_session(tenant) as session:
        found = await session.scalar(
            text(
                "SELECT count(DISTINCT evidence_item_id) FROM evidence_versions "
                "WHERE engagement_id = :e"
            ),
            {"e": engagement_id},
        )
    return int(found or 0)
