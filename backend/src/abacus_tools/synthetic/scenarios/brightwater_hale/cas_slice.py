"""The CAS slice (`--slice cas`; C-01-T44; TASK-8700; DEC-5700): Brightwater Hale's August 2026
close portfolio loaded through the closes services, honouring the `copperleaf` holdout.

Order, all after the binders slice's setup at Sep 1, 8:00 AM (which creates Copperleaf's
"2026 Close" engagement and its August close):

1. Grace Holloway imports the CAS close template "Café with Square/Shopify" (CLS-09 d) through the
   template import, never a commit (AC-20).
2. Copperleaf's plan: Raj drafts v2 (twenty-two procedures: v3 less the subscription row) and
   Priya publishes it from March; Raj drafts v3 adding "Deferred Revenue — Subscriptions" and
   Priya publishes it from June (CLS-09 a); Raj's draft v4 moves the savings statement to the
   bank feed, so the plan generates seven requests a month (CLS-09 b).
3. Priya generates the rest of "2026 Close" (twelve closes, the August one already there), Raj
   and Priya are the August close's preparer and reviewer, and Run 2 has it In progress.
4. The seven open exceptions of CLS-06 (2 Medium + 5 Low) on the August close.
5. The twenty-one other August closes of CLS-01: one `cas_monthly_close` engagement each, its
   twelve closes generated, the pair assigned and the August status set (3 + 11 + 5 + 3).

The publishes are written at the seed instant, so CLS-09's history dates (v2 Mar 6, v3 Jun 2) are
the fixture's; the plan's effective months are the seed's (DEC-5700). Not in this slice yet (the
task's progress log): the Close Planner's v1 draft (no discard path for a superseded draft), the
four CLS-06 notes (no copy in the handoff), the fake QBO company, statements, payout and payroll
files, Run 1 and Run 2 events, flux and the transaction questions.
"""

from __future__ import annotations

from dataclasses import dataclass
from datetime import timedelta
from typing import Final

from abacus_tools.synthetic.scenarios.brightwater_hale.close_slice import (
    COPPERLEAF,
    ISSUES,
    PLAN_TEMPLATE,
    PLAN_V3,
    PORTFOLIO,
    REQUEST_TEMPLATES,
    PlanRow,
    PortfolioClose,
)
from abacus_tools.synthetic.scenarios.brightwater_hale.scenario import SETUP_AT
from abacus_tools.synthetic.scenarios.brightwater_hale.slices import register_slice
from abacus_tools.synthetic.scenarios.brightwater_hale.timeline import Event

SLICE: Final = "cas"
NEEDS: Final = ("binders",)  # Copperleaf's close engagement and its August close

TEMPLATE_KEY: Final = "cafe-square-shopify"
TEMPLATE_VERSION: Final = 1
SUBSCRIPTIONS: Final = "Deferred Revenue — Subscriptions"
SAVINGS: Final = "Business Savings (Front Range Bank) ••4436"
YEAR: Final = 2026
AUGUST: Final = 8
# Where the requests generated by the plan fall due (CLS-09 "Requests 8": BD due days).
REQUEST_DUE_BUSINESS_DAY: Final = 3


@dataclass(frozen=True, slots=True)
class PlanVersion:
    version: int
    drafted_by: str  # initials
    published_by: str | None  # None: the draft stays a draft
    effective_from: str | None  # "YYYY-MM"


PLAN_VERSIONS: Final = (
    PlanVersion(2, "RM", "PR", "2026-03"),
    PlanVersion(3, "RM", "PR", "2026-06"),
    PlanVersion(4, "RM", None, None),
)

# Firm roles of the CAS seats, for the engagement role each holds on a portfolio close.
ENGAGEMENT_ROLE: Final = {
    "PR": "engagement_partner",
    "HV": "manager",
    "RF": "senior",
    "EW": "senior",
    "RM": "senior",
    "IV": "staff",
    "EG": "staff",
}


def v2_rows() -> tuple[PlanRow, ...]:
    """v2: v3 before the subscription launch (CLS-09 history: v3 "Added Deferred Revenue —
    Subscriptions after the subscription launch")."""
    return tuple(r for r in PLAN_V3 if r.account != SUBSCRIPTIONS)


def v2_request_templates() -> tuple[str, ...]:
    return tuple(t for t in REQUEST_TEMPLATES if t != "Subscription billing report")


def v4_requests() -> tuple[str, ...]:
    """v4: the savings statement comes from the bank feed, so its request goes (7 a month)."""
    return tuple(t for t in REQUEST_TEMPLATES if not t.startswith("Business Savings"))


def others() -> tuple[PortfolioClose, ...]:
    """The twenty-one August closes beside Copperleaf's (CLS-01)."""
    return tuple(c for c in PORTFOLIO if c.client != COPPERLEAF)


def copperleaf_close() -> PortfolioClose:
    return next(c for c in PORTFOLIO if c.client == COPPERLEAF)


def events() -> list[Event]:
    out = [
        Event(
            f"cas:template:{TEMPLATE_KEY}",
            SETUP_AT + timedelta(minutes=30),
            "closes.template_imported",
            "GH",
            SLICE,
            {"key": TEMPLATE_KEY, "version": TEMPLATE_VERSION, "name": PLAN_TEMPLATE},
        )
    ]
    out += [
        Event(
            f"cas:copperleaf:plan-v{v.version}",
            SETUP_AT + timedelta(hours=1, minutes=v.version),
            "closes.plan_version_seeded",
            v.published_by or v.drafted_by,
            SLICE,
            {
                "version": v.version,
                "drafted_by": v.drafted_by,
                "published_by": v.published_by,
                "effective_from": v.effective_from,
            },
            client=COPPERLEAF,
        )
        for v in PLAN_VERSIONS
    ]
    c1 = copperleaf_close()
    out.append(
        Event(
            "cas:copperleaf:closes",
            SETUP_AT + timedelta(hours=1, minutes=10),
            "closes.year_generated",
            "PR",
            SLICE,
            {"ref": c1.ref, "year": YEAR},
            client=COPPERLEAF,
        )
    )
    out += [
        Event(
            f"cas:copperleaf:issue:{i}",
            SETUP_AT + timedelta(hours=1, minutes=20 + i),
            "closes.exception_seeded",
            "RM",
            SLICE,
            {"index": i},
            client=COPPERLEAF,
        )
        for i in range(len(ISSUES))
    ]
    out += [
        Event(
            f"cas:portfolio:{c.ref}",
            SETUP_AT + timedelta(hours=2, minutes=int(c.ref[1:])),
            "closes.portfolio_close_seeded",
            "PR",
            SLICE,
            {"ref": c.ref, "status": c.status},
            client=c.client,
        )
        for c in others()
    ]
    return out


register_slice(SLICE)(events)

