"""The one-off database bootstrap task (Q-01-T20; ADR-014; TASK-014). PROTECTED.

Run once per environment, before the first migration, by the `bootstrap` ECS task (the image's
`bootstrap` entrypoint), and again whenever a role password is rotated. As the managed-database
admin it applies `migrations/bootstrap.sql` (the roles, their attributes, the extensions and the
default privileges; idempotent) and then sets each app role's password from the environment the
task definition injects from Secrets Manager. Nothing is printed but the role names it touched:
never a password, never a DSN.

Environment (all required): `ABACUS_DB_HOST`, `ABACUS_DB_MASTER_USER`,
`ABACUS_DB_MASTER_PASSWORD` (the RDS-managed master secret's keys) and
`ABACUS_BOOTSTRAP_<ROLE>_PASSWORD` for owner, app, relay, identity and ops. TLS follows
`db_connect` (verify-full against `ABACUS_DATABASE_CA_FILE`).
"""

from __future__ import annotations

import asyncio
import os
import sys
from pathlib import Path
from urllib.parse import quote

from abacus_tools.db_connect import connect

ROLES = ("owner", "app", "relay", "identity", "ops")
SQL = Path(__file__).resolve().parents[2] / "migrations" / "bootstrap.sql"
_MIN_PASSWORD = 32


class BootstrapError(Exception):
    """A required input is missing or unusable; the message names it, never its value."""


def _required(name: str) -> str:
    value = os.environ.get(name, "")
    if not value:
        raise BootstrapError(f"{name} is not set")
    return value


def passwords() -> dict[str, str]:
    """Each app role's password, checked for length (generated by fill-secrets.sh)."""
    found: dict[str, str] = {}
    for role in ROLES:
        name = f"ABACUS_BOOTSTRAP_{role.upper()}_PASSWORD"
        value = _required(name)
        if len(value) < _MIN_PASSWORD:
            raise BootstrapError(f"{name} is shorter than {_MIN_PASSWORD} characters")
        found[f"abacus_{role}"] = value
    return found


def admin_dsn() -> str:
    host = _required("ABACUS_DB_HOST")
    user = quote(_required("ABACUS_DB_MASTER_USER"), safe="")
    password = quote(_required("ABACUS_DB_MASTER_PASSWORD"), safe="")
    database = os.environ.get("ABACUS_DB_NAME", "abacus")
    return f"postgresql://{user}:{password}@{host}:5432/{database}?sslmode=verify-full"


async def run() -> list[str]:
    roles = passwords()
    connection = await connect(admin_dsn())
    try:
        await connection.execute(SQL.read_text(encoding="utf-8"))
        for role, password in roles.items():
            # ALTER ROLE takes no bind parameters: quote both through the server.
            statement = await connection.fetchval(
                "SELECT format('ALTER ROLE %I PASSWORD %L', $1::text, $2::text)", role, password
            )
            await connection.execute(str(statement))
    finally:
        await connection.close()
    return sorted(roles)


def main() -> int:
    try:
        touched = asyncio.run(run())
    except BootstrapError as exc:
        print(f"bootstrap: {exc}", file=sys.stderr)
        return 2
    print(f"bootstrap: applied bootstrap.sql; passwords set for {', '.join(touched)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
