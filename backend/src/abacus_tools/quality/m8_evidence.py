"""The M8 quality rows (Q-03-T085; chapter 10 §10.13 "MVP code-complete"; Q-03 §3.2).

    python -m abacus_tools.quality.m8_evidence            # print the rows as of this checkout
    python -m abacus_tools.quality.m8_evidence --write    # refresh them in the gate file

M8 (Fri May 28, 2027) is MVP-1 code-complete. Its quality rows in
`docs/ops/gates/M8-mvp-code-complete.md` are derived here from the registers on `main`, so they
can be re-run on the pinned SHA the day both founders sign, and a row is never "ready" by hand:

- **Q-1 Back-fill closed.** `docs/quality/backfill.md` holds the 55 items: 44 back-filled
  (tranche 0 and S6-S11), 7 superseded by merged AC suites, 4 superseded with black-box suites
  on their legacy paths (Q-03-T524, T525). Each superseded row names its closing suite.
- **Q-2 Back-fill green.** The latest `docs/quality/backfill-rerun-<date>.md` has every
  back-filled task green, or each red one ticketed in the escaped-defect log.
- **Q-3 Coverage.** `fail_under = 95` in `pyproject.toml`, no coverage exception left
  (`coverage-exception.toml` gone or expired), and every red module's line floor at 97
  (`coverage-thresholds.yaml`). The measured number is CI's (`make ci-coverage`), not this tool's.
- **Q-4 Mutation floors recorded.** Every scope of `abacus_tools.quality.mutation` has a floor in
  `mutation-thresholds.yaml`; the M8 targets (85 for identity/authz and compute, 75 otherwise) are
  shown beside them.
- **Q-5 No back-fill defect above SEV3.** No escaped defect found by a back-fill row is SEV1 or
  SEV2 and still open.
- **Q-6 Every escaped defect has its layer.** Each row of `docs/quality/escaped-defects.md`
  names the layer that should have caught it.
- **Q-7 Sign-off.** Both founders, by hand, on the pinned SHA (never derived).

Exit 0 when Q-1 to Q-6 are ready, 1 otherwise (the gate may be printed any day; it is signed on
M8 only when this exits 0 on the pinned SHA).
"""

from __future__ import annotations

import argparse
import re
import sys
import tomllib
from dataclasses import dataclass
from datetime import date
from pathlib import Path
from typing import Final

from abacus.kernel.clock import system_now
from abacus_tools.quality import coverage_floors, mutation_floors
from abacus_tools.quality.mutation import SCOPES

BACKEND: Final = Path(__file__).resolve().parents[3]
ROOT: Final = BACKEND.parent
QUALITY: Final = ROOT / "docs" / "quality"
GATE: Final = ROOT / "docs" / "ops" / "gates" / "M8-mvp-code-complete.md"
START: Final = "<!-- m8-quality:start (generated by abacus_tools.quality.m8_evidence) -->"
END: Final = "<!-- m8-quality:end -->"
EXPECTED: Final = {"backfilled": 44, "superseded_ac": 7, "superseded_legacy": 4}
RED_LINE_TARGET: Final = 97
GLOBAL_FLOOR: Final = 95
MUTATION_TARGETS: Final = {"identity/authz": 85, "compute": 85}
MUTATION_DEFAULT_TARGET: Final = 75
_BACKFILLED: Final = frozenset({"back-filled", "tranche 0"})
_LEGACY_ROWS: Final = re.compile(r"\bT52[45]\b")


@dataclass(frozen=True)
class Item:
    task: str
    q03_row: str
    status: str
    suites: str


@dataclass(frozen=True)
class Check:
    key: str
    item: str
    ready: bool
    evidence: str


def register(text: str) -> list[Item]:
    """`| TASK | Zone | Area | Spec | Sprint | Q-03 row | Status | Suite or closing task |`."""
    found: list[Item] = []
    for line in text.splitlines():
        cells = [c.strip() for c in line.strip().strip("|").split("|")]
        if len(cells) == 8 and re.fullmatch(r"\d{3}", cells[0]):
            found.append(Item(cells[0], cells[5], cells[6], cells[7]))
    return found


def q1_backfill_closed(items: list[Item]) -> Check:
    backfilled = [i for i in items if i.status in _BACKFILLED]
    superseded = [i for i in items if i.status == "superseded"]
    legacy = [i for i in superseded if _LEGACY_ROWS.search(i.q03_row)]
    ac = [i for i in superseded if i not in legacy]
    other = [i for i in items if i.status not in _BACKFILLED and i.status != "superseded"]
    unnamed = [i.task for i in superseded if "`" not in i.suites and "TASK-" not in i.suites]
    counts = {
        "backfilled": len(backfilled),
        "superseded_ac": len(ac),
        "superseded_legacy": len(legacy),
    }
    ready = (
        counts == EXPECTED and not other and not unnamed and len(items) == sum(EXPECTED.values())
    )
    evidence = (
        f"`docs/quality/backfill.md`: {len(items)} items; {len(backfilled)} back-filled, "
        f"{len(ac)} superseded by merged AC suites, {len(legacy)} with legacy black-box suites "
        f"(T524/T525)"
    )
    if other:
        evidence += f"; not closed: {', '.join(f'TASK-{i.task} ({i.status})' for i in other)}"
    if unnamed:
        evidence += f"; superseded without a named suite: {', '.join(unnamed)}"
    return Check("Q-1", "All 55 back-fill items closed (44 / 7 / 4)", ready, evidence)


def latest_rerun(quality: Path = QUALITY) -> Path | None:
    reports = sorted(quality.glob("backfill-rerun-*.md"))
    return reports[-1] if reports else None


def q2_backfill_green(report: Path | None, defects_text: str) -> Check:
    item = "Back-filled suites green on the re-run, or each red one ticketed"
    if report is None:
        return Check("Q-2", item, False, "no `docs/quality/backfill-rerun-*.md` yet")
    results: dict[str, str] = {}
    for line in report.read_text(encoding="utf-8").splitlines():
        cells = [c.strip() for c in line.strip().strip("|").split("|")]
        if len(cells) == 5 and re.fullmatch(r"\d{3}", cells[0]):
            results[cells[0]] = cells[3]
    red = [t for t, r in results.items() if r != "green"]
    unticketed = [t for t in red if f"TASK-{t}" not in defects_text]
    evidence = (
        f"`docs/quality/{report.name}`: {len(results)} tasks, {len(results) - len(red)} green"
    )
    if red:
        evidence += f"; red: {', '.join(red)}"
    if unticketed:
        evidence += f"; not in the escaped-defect log: {', '.join(unticketed)}"
    return Check("Q-2", item, bool(results) and not unticketed, evidence)


def q3_coverage(backend: Path = BACKEND, today: date | None = None) -> Check:
    day = today or system_now().date()
    pyproject = tomllib.loads((backend / "pyproject.toml").read_text(encoding="utf-8"))
    report_cfg = pyproject.get("tool", {}).get("coverage", {}).get("report", {})
    fail_under = int(report_cfg.get("fail_under", 0))
    problems: list[str] = []
    if fail_under < GLOBAL_FLOOR:
        problems.append(f"fail_under is {fail_under}, not {GLOBAL_FLOOR}")
    exception = backend / "coverage-exception.toml"
    if exception.exists():
        expires = tomllib.loads(exception.read_text(encoding="utf-8")).get("expires")
        if isinstance(expires, date) and expires > day:
            problems.append(f"the DEC-10 coverage exception is live until {expires.isoformat()}")
        else:
            problems.append("`coverage-exception.toml` has expired but is still in the tree")
    floors = coverage_floors.parse(
        (backend / "coverage-thresholds.yaml").read_text(encoding="utf-8")
    )
    below = sorted(f"{m} {p}" for m, p in floors.get("line", {}).items() if p < RED_LINE_TARGET)
    if below:
        problems.append(f"red line floors under {RED_LINE_TARGET}: {', '.join(below)}")
    evidence = (
        f"`fail_under = {fail_under}`; "
        + ("; ".join(problems) if problems else f"every red line floor at {RED_LINE_TARGET}")
        + "; the measured figure is CI's `make ci-coverage` on the pinned SHA"
    )
    return Check("Q-3", "Coverage 95% global and 97% red", not problems, evidence)


def q4_mutation(backend: Path = BACKEND) -> Check:
    floors = mutation_floors.parse(
        (backend / "mutation-thresholds.yaml").read_text(encoding="utf-8")
    )
    missing = sorted(set(SCOPES) - set(floors))
    under = sorted(
        f"{scope} {floor}/{MUTATION_TARGETS.get(scope, MUTATION_DEFAULT_TARGET)}"
        for scope, floor in floors.items()
        if floor < MUTATION_TARGETS.get(scope, MUTATION_DEFAULT_TARGET)
    )
    evidence = f"`mutation-thresholds.yaml`: {len(floors)} of {len(SCOPES)} scopes recorded"
    if missing:
        evidence += f"; no floor: {', '.join(missing)}"
    if under:
        evidence += f"; under the M8 target (floor/target): {', '.join(under)}"
    return Check("Q-4", "Mutation floors recorded for every red scope", not missing, evidence)


def defects(text: str) -> list[dict[str, str]]:
    lines = [ln for ln in text.splitlines() if ln.startswith("|")]
    if not lines:
        return []
    header = [c.strip() for c in lines[0].strip().strip("|").split("|")]
    found: list[dict[str, str]] = []
    for line in lines[2:]:
        cells = [c.strip() for c in line.strip().strip("|").split("|")]
        if cells and cells[0].startswith("ED-"):
            found.append(dict(zip(header, cells, strict=False)))
    return found


def q5_backfill_severity(rows: list[dict[str, str]], backfill_rows: set[str]) -> Check:
    found_by_backfill = [r for r in rows if any(t in r.get("Found by", "") for t in backfill_rows)]
    severe = [
        r["ID"]
        for r in found_by_backfill
        if r.get("Severity") in ("SEV1", "SEV2") and r.get("State", "").lower() != "fixed"
    ]
    evidence = (
        f"`docs/quality/escaped-defects.md`: {len(found_by_backfill)} defects found by back-fill "
        f"rows; " + (f"open above SEV3: {', '.join(severe)}" if severe else "none open above SEV3")
    )
    return Check("Q-5", "No back-fill defect above SEV3", not severe, evidence)


def q6_layers(rows: list[dict[str, str]]) -> Check:
    missing = [r["ID"] for r in rows if not r.get("Should have been caught by", "").strip("— ")]
    evidence = f"`docs/quality/escaped-defects.md`: {len(rows)} findings; " + (
        f"no layer: {', '.join(missing)}" if missing else "each names its layer"
    )
    return Check("Q-6", "Every escaped-defect finding has its layer", not missing, evidence)


def checks(today: date | None = None) -> list[Check]:
    items = register((QUALITY / "backfill.md").read_text(encoding="utf-8"))
    defects_text = (QUALITY / "escaped-defects.md").read_text(encoding="utf-8")
    rows = defects(defects_text)
    backfill_rows = {
        f"Q-03-{t.strip()}"
        for i in items
        for t in i.q03_row.split(",")
        if re.fullmatch(r"T\d{3}", t.strip())
    }
    return [
        q1_backfill_closed(items),
        q2_backfill_green(latest_rerun(), defects_text),
        q3_coverage(today=today),
        q4_mutation(),
        q5_backfill_severity(rows, backfill_rows),
        q6_layers(rows),
    ]


def table(found: list[Check], sha: str | None, day: date) -> str:
    head = (
        f"Derived {day.isoformat()}"
        + (f" on `{sha}`" if sha else "")
        + " by `python -m abacus_tools.quality.m8_evidence`.\n\n"
        + "| # | Quality row | Evidence | State |\n|---|---|---|---|\n"
    )
    body = "".join(
        f"| {c.key} | {c.item} | {c.evidence} | {'ready' if c.ready else 'not ready'} |\n"
        for c in found
    )
    sign = (
        "| Q-7 | Both founders sign the quality rows (Fri May 28, 2027) "
        "| the sign-off table below | by hand |\n"
    )
    return head + body + sign


def write(gate: Path, block: str) -> None:
    text = gate.read_text(encoding="utf-8")
    start, end = text.index(START), text.index(END)
    gate.write_text(text[: start + len(START)] + "\n" + block + text[end:], encoding="utf-8")


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(prog="abacus_tools.quality.m8_evidence", description=__doc__)
    parser.add_argument("--write", action="store_true", help="refresh the rows in the gate file")
    parser.add_argument("--sha", help="the pinned SHA the rows were derived on")
    args = parser.parse_args(argv)
    day = system_now().date()
    found = checks(day)
    block = table(found, args.sha, day)
    if args.write:
        write(GATE, block)
    print(block)
    return 0 if all(c.ready for c in found) else 1


if __name__ == "__main__":
    sys.exit(main())
